use crate::aggregate::Report;

use super::{ascii_bar, fmt_num};

pub fn render(report: &Report, top_models: usize) -> String {
    let o = &report.overview;
    let mut out = String::new();

    out.push_str("# AI Stats — Usage Report\n\n");
    out.push_str(&format!(
        "**Period:** {} → {} (UTC)  \n",
        o.since.format("%Y-%m-%d %H:%M"),
        o.until.format("%Y-%m-%d %H:%M")
    ));
    out.push_str(&format!(
        "**Providers:** {}\n\n",
        if o.providers.is_empty() {
            "none".to_string()
        } else {
            o.providers.join(", ")
        }
    ));

    out.push_str("## Overview\n\n");
    out.push_str("| Metric | Value |\n|---|---|\n");
    out.push_str(&format!("| Requests | {} |\n", fmt_num(o.total_requests)));
    out.push_str(&format!(
        "| Input tokens | {} |\n",
        fmt_num(o.total_input_tokens)
    ));
    out.push_str(&format!(
        "| Output tokens | {} |\n",
        fmt_num(o.total_output_tokens)
    ));
    out.push_str(&format!(
        "| Cached input tokens | {} |\n",
        fmt_num(o.total_cached_tokens)
    ));
    out.push_str(&format!(
        "| **Total tokens** | **{}** |\n",
        fmt_num(o.total_tokens)
    ));
    out.push_str(&format!(
        "| **Total cost (USD)** | **${:.4}**{} |\n",
        o.total_cost_usd,
        if o.cost_partially_estimated {
            " *(partially estimated)*"
        } else {
            ""
        }
    ));
    out.push('\n');

    if !report.by_provider.is_empty() {
        out.push_str("## By Provider\n\n");
        out.push_str("| Provider | Requests | Input | Output | Total | Cost (USD) |\n|---|---:|---:|---:|---:|---:|\n");
        for p in &report.by_provider {
            out.push_str(&format!(
                "| {} | {} | {} | {} | {} | ${:.4}{} |\n",
                p.provider,
                fmt_num(p.requests),
                fmt_num(p.input_tokens),
                fmt_num(p.output_tokens),
                fmt_num(p.total_tokens),
                p.cost_usd,
                if p.cost_estimated { " *(est.)*" } else { "" }
            ));
        }
        out.push('\n');
    }

    if !report.by_model.is_empty() {
        out.push_str(&format!("## Top {top_models} Models by Tokens\n\n"));
        out.push_str("| Provider | Model | Requests | Input | Output | Total | Cost (USD) |\n|---|---|---:|---:|---:|---:|---:|\n");
        for m in report.by_model.iter().take(top_models) {
            let cost = match m.cost_usd {
                Some(c) => format!(
                    "${:.4}{}",
                    c,
                    if m.cost_estimated { " *(est.)*" } else { "" }
                ),
                None => "n/a".to_string(),
            };
            out.push_str(&format!(
                "| {} | {} | {} | {} | {} | {} | {} |\n",
                m.provider,
                m.model,
                fmt_num(m.requests),
                fmt_num(m.input_tokens),
                fmt_num(m.output_tokens),
                fmt_num(m.total_tokens),
                cost
            ));
        }
        out.push('\n');
    }

    if !report.time_series.is_empty() {
        out.push_str(&format!(
            "## Time Series ({})\n\n",
            report.granularity.as_str()
        ));
        out.push_str("| Bucket | Total Tokens | Cost (USD) | Chart |\n|---|---:|---:|---|\n");
        let max_tokens = report
            .time_series
            .iter()
            .map(|r| r.total_tokens)
            .max()
            .unwrap_or(0) as f64;
        for r in &report.time_series {
            out.push_str(&format!(
                "| {} | {} | ${:.4} | `{}` |\n",
                r.label,
                fmt_num(r.total_tokens),
                r.cost_usd,
                ascii_bar(r.total_tokens as f64, max_tokens, 20)
            ));
        }
        out.push('\n');
    }

    out.push_str(&format!(
        "\n---\n*Generated by ai-stats on {}*\n",
        chrono::Utc::now().format("%Y-%m-%d %H:%M UTC")
    ));

    out
}
